#!/usr/bin/env bash
# higgsfield-motion-saas setup, Linux. Run once per machine. Idempotent.
# build_tools.sh compiles encode/mux/extract with swiftc against AVFoundation, which is macOS-only.
# This installs the ffmpeg-backed ports from scripts/code/linux/ into scripts/code/bin/ under the
# same names, so render_film.sh and the SKILL.md command lines work unchanged.
set -uo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN="$DIR/code/bin"
mkdir -p "$BIN"
ok=1

NODE_MAJOR=$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)
if [ "$NODE_MAJOR" -ge 21 ] 2>/dev/null; then echo "node      ok ($(node -v))"; else echo "node      FAIL: need Node 21+, found ${NODE_MAJOR}"; ok=0; fi

if command -v ffmpeg >/dev/null && command -v ffprobe >/dev/null; then
  echo "ffmpeg    ok ($(ffmpeg -version | head -1 | cut -d' ' -f3))"
else
  echo "ffmpeg    FAIL: apt install ffmpeg (it replaces AVFoundation here)"; ok=0
fi

# Import the submodules, not the packages: a wheel built for another Python ABI imports as a
# package and fails only on the submodule. Use python3 -m pip, never a bare pip.
if python3 -c 'import numpy; from PIL import Image' 2>/dev/null; then
  echo "python    ok (numpy $(python3 -c 'import numpy;print(numpy.__version__)'), Pillow $(python3 -c 'from PIL import Image;print(Image.__version__)'))"
else
  echo "python    FAIL: python3 -m pip install --ignore-installed numpy Pillow"; ok=0
fi

BR="${HFT_BROWSER:-}"
if [ -z "$BR" ]; then
  for p in chromium chromium-browser google-chrome google-chrome-stable brave-browser microsoft-edge; do
    c=$(command -v "$p" 2>/dev/null) && [ -n "$c" ] && BR="$c" && break
  done
fi
if [ -z "$BR" ] && [ -n "${PLAYWRIGHT_BROWSERS_PATH:-}" ]; then
  for p in "$PLAYWRIGHT_BROWSERS_PATH"/chromium*/chrome-linux/chrome "$PLAYWRIGHT_BROWSERS_PATH"/chromium; do
    [ -x "$p" ] && BR="$p" && break
  done
fi
if [ -n "$BR" ]; then echo "browser   ok ($BR)"; else echo "browser   FAIL: install chromium or set HFT_BROWSER"; ok=0; fi

# Chromium refuses to run as root without --no-sandbox (crbug.com/638180), and in a container
# /dev/shm is usually tiny. capture.mjs spawns $HFT_BROWSER directly, so a wrapper that appends
# these flags needs no change to capture.mjs or cdp.mjs.
make_wrapper() {
  local real="$1" dest="$2"
  cat > "$dest" <<WRAPPER
#!/usr/bin/env bash
# Auto-generated by setup-linux.sh. Launches Chromium with the flags a Linux container needs.
exec "$real" --no-sandbox --disable-dev-shm-usage --disable-gpu "\$@"
WRAPPER
  chmod +x "$dest"
}

for t in encode mux extract; do
  src="$DIR/code/linux/$t"
  if [ ! -f "$src" ]; then echo "tool      MISSING $t"; ok=0; continue; fi
  install -m 0755 "$src" "$BIN/$t"
  echo "tool      installed $t -> code/bin/$t"
done
chmod +x "$DIR/code/linux/render_film.sh" "$DIR/code/linux/stills.sh" 2>/dev/null

command -v zsh >/dev/null || echo "note      zsh not installed: use code/linux/render_film.sh and code/linux/stills.sh (bash ports) instead of the zsh originals"
echo "note      After Effects (ae.sh, *.jsx) does not run on Linux - use the code pipeline"
if [ -n "$BR" ]; then
  make_wrapper "$BR" "$BIN/chrome-wrapper"
  echo "browser   wrapper written: $BIN/chrome-wrapper (adds --no-sandbox)"
fi
[ -n "$BR" ] && echo "browser:  export HFT_BROWSER=\"$BIN/chrome-wrapper\""
[ "$ok" = 1 ] && echo "setup OK" || { echo "setup finished with problems"; exit 1; }
